"""
RepoMind-AI HTML Report Generator.
"""

from pathlib import Path
from datetime import datetime
from html import escape


def generate_html(
    result,
    repository_name="repository",
    output_dir="reports",
):
    """Generate an HTML report from the final AI result."""

    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)

    report_text = escape(str(result))
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    html = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport"
          content="width=device-width, initial-scale=1.0">

    <title>RepoMind-AI Analysis</title>

    <style>
        body {{
            font-family: -apple-system, BlinkMacSystemFont,
                         "Segoe UI", sans-serif;
            max-width: 1000px;
            margin: 40px auto;
            padding: 0 24px;
            line-height: 1.6;
            background: #f5f5f5;
            color: #222;
        }}

        .container {{
            background: white;
            padding: 40px;
            border-radius: 12px;
            box-shadow: 0 4px 20px rgba(0, 0, 0, 0.08);
        }}

        h1 {{
            margin-bottom: 8px;
        }}

        .metadata {{
            color: #666;
            margin-bottom: 30px;
        }}

        .analysis {{
            white-space: pre-wrap;
            font-family: ui-monospace, SFMono-Regular,
                         Menlo, Monaco, Consolas, monospace;
            background: #fafafa;
            padding: 24px;
            border-radius: 8px;
            overflow-x: auto;
        }}

        footer {{
            margin-top: 30px;
            color: #777;
            font-size: 14px;
        }}
    </style>
</head>

<body>

<div class="container">

    <h1>RepoMind-AI Repository Analysis</h1>

    <div class="metadata">
        <strong>Repository:</strong>
        {escape(repository_name)}
        <br>
        <strong>Generated:</strong>
        {timestamp}
    </div>

    <h2>Final AI Analysis</h2>

    <div class="analysis">{report_text}</div>

    <footer>
        Generated by RepoMind-AI
    </footer>

</div>

</body>
</html>
"""

    file_path = output_path / "repository_analysis.html"
    file_path.write_text(html, encoding="utf-8")

    return file_path
