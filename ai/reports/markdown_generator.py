"""
RepoMind-AI Markdown Report Generator.
"""

from pathlib import Path
from datetime import datetime


def generate_markdown(
    result,
    repository_name="repository",
    output_dir="reports",
):
    """Generate a professional Markdown report."""

    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)

    report_text = str(result)
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    sections = {
        "EXECUTIVE SUMMARY": "## Executive Summary",
        "REPOSITORY OVERVIEW": "## Repository Overview",
        "ARCHITECTURE FINDINGS": "## Architecture Findings",
        "CODE QUALITY FINDINGS": "## Code Quality Findings",
        "DOCUMENTATION FINDINGS": "## Documentation Findings",
        "SECURITY FINDINGS": "## Security Findings",
        "RISK ASSESSMENT": "## Risk Assessment",
        "RECOMMENDATIONS": "## Recommendations",
    }

    formatted_report = report_text

    for heading, markdown_heading in sections.items():
        formatted_report = formatted_report.replace(
            heading,
            markdown_heading,
        )

    markdown = f"""# RepoMind-AI Repository Analysis

**Repository:** {repository_name}

**Generated:** {timestamp}

---

{formatted_report}

---

## About This Report

This report was generated by RepoMind-AI using
repository information collected from GitHub and
analyzed by multiple AI agents.

### Grounding Principle

Findings should be based only on repository information
available to the AI analysis pipeline.

---

*Generated by RepoMind-AI*
"""

    file_path = output_path / "repository_analysis.md"

    file_path.write_text(
        markdown,
        encoding="utf-8",
    )

    return file_path
